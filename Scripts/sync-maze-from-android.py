#!/usr/bin/env python3
r"""Copies the Android Minik Maze game into Maze/game for the iOS build.

Minik Maze is a Godot 4.7.2 project, and iOS runs the very same project: the game is copied, not ported.
This takes the committed files of the Android repository (C:\Projects\MinikMaze, app/src/main/assets) and of
the shared family catalogue (C:\Projects\MinikFamilyServices, android/src/main/assets/minik-family), and makes
three iOS changes, each checked so that a changed Android file stops the copy instead of being patched wrongly:

1. project.godot gets one autoload, res://ios/maze_services_ios.gd: the iOS stand-in for the Android host's
   MazeServices plugin (purchase, grown-up gate, privacy page, More Minik apps); and ios/app-name.he.po as its
   only translation, for the Hebrew Home Screen name.
2. world.gd shows the online records buttons only when the platform offers them: the Maze brief keeps the
   Firebase records on Android ("Intentionally excluded by brief" for iOS in FEATURE_MATRIX.md).
3. Every image, font and sound is exported as it is (importer "keep"): the game reads them as plain files
   (Image.load_from_file, FileAccess), as on Android, where nothing is imported.

Maze/game/ios/ and Maze/game/export_presets.cfg are iOS-only and never touched. Maze/android-source.json
records the two source commits and every copied file. Run from the repository root:

    python Scripts/sync-maze-from-android.py
"""
import hashlib
import io
import json
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAME = ROOT / 'Maze' / 'game'
MANIFEST = ROOT / 'Maze' / 'android-source.json'
ANDROID = Path(r'C:\Projects\MinikMaze')
FAMILY = Path(r'C:\Projects\MinikFamilyServices')
ANDROID_ASSETS = 'app/src/main/assets/'
FAMILY_ASSETS = 'android/src/main/assets/'
GIT = shutil.which('git') or r'C:\Program Files\Git\cmd\git.exe'

# Generated by the Godot editor when it opens the project; Android's Gradle build writes its own copy.
SKIPPED_PREFIXES = ('.godot/', 'qa-output/')
# Files the game opens directly, never through load(): exported unchanged.
KEPT_EXTENSIONS = {'.png', '.webp', '.jpg', '.jpeg', '.svg', '.ttf', '.otf', '.mp3', '.wav', '.ogg'}
KEEP_IMPORT = b'[remap]\n\nimporter="keep"\n'

AUTOLOAD = b'\n[autoload]\n\nMazeServicesIOS="*res://ios/maze_services_ios.gd"\n'
# The Home Screen name in Hebrew (Android values-iw app_name): Godot's iOS export writes he.lproj from it.
APP_NAME = b'\n[internationalization]\n\nlocale/translations=PackedStringArray("res://ios/app-name.he.po")\n'
RECORDS_ANDROID = b'\tif platform!=null and not test_mode:\n\t\tbox.add_child(button(text.t("Online records")'
RECORDS_IOS = (b'\t# iOS (Maze/README.md): the online records stay on Android; the iOS services have no load_records.\n'
               b'\tif platform!=null and not test_mode and platform.has_method("load_records"):\n'
               b'\t\tbox.add_child(button(text.t("Online records")')


def stop(message):
    print('STOPPED: ' + message)
    sys.exit(1)


def git(repo, *args):
    result = subprocess.run([GIT, '-c', 'core.autocrlf=false', *args], cwd=repo, capture_output=True)
    if result.returncode:
        stop(f'git {" ".join(args)} failed in {repo}:\n{result.stderr.decode("utf-8", "replace").strip()}')
    return result.stdout


def committed_files(repo, prefix):
    """{path below prefix: bytes} of the committed HEAD, exactly as stored."""
    files = {}
    with tarfile.open(fileobj=io.BytesIO(git(repo, 'archive', '--format=tar', 'HEAD', prefix)), mode='r:') as tar:
        for member in tar:
            if member.isfile():
                files[member.name[len(prefix):]] = tar.extractfile(member).read()
    if not files:
        stop(f'{repo} has no committed files under {prefix}')
    return files


def replace_once(name, data, old, new):
    if data.count(old) != 1:
        stop(f'{name} changed on Android: the iOS change no longer fits. Update {Path(__file__).name}.')
    return data.replace(old, new)


def main():
    android_commit = git(ANDROID, 'rev-parse', 'HEAD').decode().strip()
    family_commit = git(FAMILY, 'rev-parse', 'HEAD').decode().strip()
    files = {}
    for path, data in committed_files(ANDROID, ANDROID_ASSETS).items():
        if path.startswith(SKIPPED_PREFIXES) or path.endswith('.import'):
            continue
        files[path] = data
    for path, data in committed_files(FAMILY, FAMILY_ASSETS + 'minik-family/').items():
        files['minik-family/' + path] = data

    for section in (b'[autoload]', b'[internationalization]'):
        if section in files['project.godot']:
            stop(f'project.godot now has {section.decode()} on Android. Update the sync script.')
    files['project.godot'] = files['project.godot'].rstrip(b'\n') + b'\n' + AUTOLOAD + APP_NAME
    files['world.gd'] = replace_once('world.gd', files['world.gd'], RECORDS_ANDROID, RECORDS_IOS)
    for path in list(files):
        if Path(path).suffix.lower() in KEPT_EXTENSIONS:
            files[path + '.import'] = KEEP_IMPORT
    for path in files:
        if path.startswith('ios/') or path == 'export_presets.cfg':
            stop(f'Android now has {path}, which is an iOS-only file here.')

    previous = set()
    if MANIFEST.exists():
        previous = set(json.loads(MANIFEST.read_text(encoding='utf-8'))['files'])
    for path in sorted(previous - set(files)):
        target = GAME / path
        if target.exists():
            target.unlink()
            print(f'removed {path}')
    written = 0
    for path, data in sorted(files.items()):
        target = GAME / path
        if not target.exists() or target.read_bytes() != data:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            written += 1
    MANIFEST.write_text(json.dumps({
        'android': {'repository': 'MinikMaze', 'commit': android_commit, 'path': ANDROID_ASSETS},
        'family': {'repository': 'MinikFamilyServices', 'commit': family_commit, 'path': FAMILY_ASSETS + 'minik-family/'},
        'ios_changes': ['project.godot: autoload ios/maze_services_ios.gd, translation ios/app-name.he.po',
                        'world.gd: online records only when the platform has load_records',
                        'images, fonts and sounds: importer "keep"'],
        'files': {path: hashlib.sha256(data).hexdigest() for path, data in sorted(files.items())},
    }, indent=1, sort_keys=False) + '\n', encoding='utf-8')
    print(f'Minik Maze Android {android_commit[:7]}, family {family_commit[:7]}: {len(files)} files, {written} written.')


if __name__ == '__main__':
    main()
